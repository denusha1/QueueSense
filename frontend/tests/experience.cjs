const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base=process.env.BASE_URL||'http://127.0.0.1:3001';
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:375,height:812}});
 const page=await context.newPage();
 try{
  await page.goto(base);
  const session=await context.request.post(base+'/api/auth/demo',{headers:{Origin:base},data:{role:'admin'}});
  assert.equal(session.status(),200);
  const write=async(path,data,method='POST')=>{const r=await context.request.fetch(base+'/api/service/'+path,{method,headers:{Origin:base},data});assert(r.ok(),await r.text());return r.json();};
  const code='E'+Array.from({length:7},()=>String.fromCharCode(65+Math.floor(Math.random()*26))).join('');
  const dep=await write('admin/departments',{code,name:'Experience browser test '+code,location:'Synthetic test',queue_threshold:10});
  const staff=await write('admin/staff',{department_id:dep.id,display_name:'Experience test clinician'});
  await write('staff/'+staff.id+'/availability',{status:'available'},'PATCH');
  const token=await write('queue/check-in',{department_id:dep.id});
  await write('staff/'+staff.id+'/call-next');
  await write('queue/'+token.id+'/status',{status:'in_service'},'PATCH');
  await write('queue/'+token.id+'/status',{status:'completed'},'PATCH');
  await page.goto(base+'/patient/'+token.public_key);
  await page.getByRole('heading',{name:'How was your visit?'}).waitFor();
  await page.getByLabel('Experience rating').selectOption('4');
  await page.getByLabel('Comments (optional)').fill('Clear updates helped during my wait.');
  await page.getByRole('button',{name:'Submit feedback'}).click();
  await page.getByText('Thank you. Your feedback has been recorded.').waitFor();
  await page.reload();
  await page.getByText('Thank you. Your feedback has been recorded.').waitFor();
  await page.goto(base+'/workspace/admin?view=feedback');
  await page.getByLabel('Department',{exact:true}).selectOption(dep.id);
  await page.getByText('Clear updates helped during my wait.',{exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.goto(base+'/workspace/admin?view=health');
  await page.getByText('PostgreSQL LISTEN/NOTIFY delivery verified.',{exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  const manifest=await (await context.request.get(base+'/manifest.webmanifest')).json();
  assert.equal(manifest.display,'standalone');
  for(const icon of manifest.icons)assert.equal((await context.request.get(base+icon.src)).status(),200);
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.reload();
  await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
  const cached=await page.evaluate(async()=>{const result=[];for(const key of await caches.keys()){for(const request of await (await caches.open(key)).keys())result.push(new URL(request.url).pathname);}return result;});
  assert.deepEqual(cached,['/offline.html']);
  await context.setOffline(true);
  await page.goto(base+'/patient/'+token.public_key);
  await page.getByRole('heading',{name:'You’re offline'}).waitFor();
  assert.equal(await page.getByText(token.token_no.toString(),{exact:true}).count(),0);
  console.log('PASS: feedback submission and persistence, mobile feedback/health, manifest/icons, privacy-safe offline navigation.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
